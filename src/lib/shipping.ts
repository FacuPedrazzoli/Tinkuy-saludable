interface ShippingQuote {
  method: 'ANDREANI' | 'PICKUP';
  name: string;
  price: number;
  estimatedDays: string;
  freeFrom?: number;
}

export async function getShippingQuotes(
  postalCode: string,
  cartTotal: number,
  weight: number = 1
): Promise<ShippingQuote[]> {
  const quotes: ShippingQuote[] = [];

  quotes.push({
    method: 'PICKUP',
    name: 'Retiro en nuestro local',
    price: 0,
    estimatedDays: 'Hoy mismo si pedís antes de las 14hs',
    freeFrom: 0,
  });

  const isCapitalGBA = await validateAndreaniZone(postalCode);
  if (isCapitalGBA) {
    const andreaniPrice = await calculateAndreaniPrice(postalCode, weight);
    const freeShippingThreshold = 15000;

    quotes.push({
      method: 'ANDREANI',
      name: 'Envío a domicilio (Andreani)',
      price: cartTotal >= freeShippingThreshold ? 0 : andreaniPrice,
      estimatedDays: '2-5 días hábiles',
      freeFrom: freeShippingThreshold,
    });
  } else {
    quotes.push({
      method: 'ANDREANI',
      name: 'Envío a domicilio',
      price: 0,
      estimatedDays: 'Consultar disponibilidad',
    });
  }

  return quotes;
}

